import assert from 'node:assert/strict';
import test from 'node:test';

import { ESLint } from 'eslint';

const lint = new ESLint();
const webFile = 'apps/web/src/features/architecture-probe.ts';
const apiFile = 'apps/api/src/routes/architecture-probe.ts';
const boundaryRule = 'architecture/no-cross-app-imports';
const commentRule = 'architecture/no-implementation-comments';
const relevantRules = [
  boundaryRule,
  commentRule,
  'no-restricted-imports',
  'no-restricted-globals',
  'no-restricted-syntax',
];

async function reports(source, filePath = webFile) {
  const [result] = await lint.lintText(source, { filePath });
  assert.ok(result);
  assert.equal(result.fatalErrorCount, 0);
  return result.messages
    .filter((message) => relevantRules.includes(message.ruleId))
    .map((message) => message.ruleId);
}

test('Web and API implementation cannot import one another', async () => {
  const crossAppSources = [
    "import { app } from '../../../api/src/app';",
    "export { app } from '@/../../api/src/app';",
    "import config from '@/../../api/src/config/maintenance.ts?raw';",
    "import migration from '@/../../api/drizzle/0000_blue_firebird.sql?raw';",
    "import config from '/@fs/server/config.ts';",
    "import type { AppEnv } from '@app-template/api/types';",
    "type Env = import('../../../api/src/types.js').AppEnv;",
    'export const load = () => import(`../../../api/src/app`);',
    "export * from '../../../../api/[...route]';",
    'export const load = (path: string) => import(path);',
    "export const modules = import.meta.glob('../../../api/src/**/*.ts', { eager: true });",
    "export const modules = import.meta['glob']('../../../api/src/**/*.ts');",
  ];
  for (const source of crossAppSources) {
    assert.deepEqual(await reports(source), [boundaryRule], source);
  }
  assert.deepEqual(await reports("import { App } from '../../../web/src/App';", apiFile), [
    boundaryRule,
  ]);
  assert.deepEqual(await reports("import type { paths } from '@/generated/openapi';"), []);
  assert.deepEqual(await reports("import css from '@/styles/index.css?raw';"), []);
  assert.deepEqual(await reports("import type { AppEnv } from '../types.js';", apiFile), []);
  assert.deepEqual(
    await reports("export const load = () => import('@/pages/admin/AdminPage');"),
    [],
  );
});

test('product UI uses declarative state rather than low-level effects and timers', async () => {
  for (const source of [
    "import { useEffect as externalSync } from 'react';",
    "import { useLayoutEffect } from 'react';",
    "import { useInsertionEffect } from 'react';",
    "import * as React from 'react';",
    "import React from 'react';",
  ]) {
    assert.deepEqual(await reports(source), ['no-restricted-imports'], source);
  }
  assert.deepEqual(await reports("void import('react');"), ['no-restricted-syntax']);
  assert.deepEqual(await reports('void import(`react`);'), ['no-restricted-syntax']);
  assert.deepEqual(
    await reports('const { setTimeout: schedule } = window; schedule(() => {}, 100);'),
    ['no-restricted-syntax'],
  );
  assert.deepEqual(await reports('({ ["requestAnimationFrame"]: frame } = globalThis);'), [
    'no-restricted-syntax',
  ]);
  for (const source of [
    'setTimeout(() => {}, 100);',
    'window.setInterval(() => {}, 100);',
    'self.requestAnimationFrame(() => {});',
    'globalThis["requestIdleCallback"](() => {});',
  ]) {
    assert.deepEqual(await reports(source), ['no-restricted-globals'], source);
  }
  assert.deepEqual(await reports("import { useState } from 'react';"), []);
  assert.deepEqual(
    await reports("import { useEffect } from 'react';", 'apps/web/src/providers/example.ts'),
    [],
  );
  assert.deepEqual(await reports('setTimeout(() => {}, 100);', apiFile), []);
});

test('production source rejects comments and inline lint bypasses', async () => {
  assert.deepEqual(await reports('// Explain the workaround\nexport {};'), [commentRule]);
  assert.deepEqual(await reports('/** Document the workaround */\nexport {};', apiFile), [
    commentRule,
  ]);
  assert.deepEqual(await reports('/* eslint-disable */\nsetTimeout(() => {}, 100);'), [
    commentRule,
    'no-restricted-globals',
  ]);
  assert.deepEqual(await reports('export const url = "https://example.com";'), []);
  assert.deepEqual(
    await reports(
      '// @ts-expect-error An invalid value must fail type checking.\nconst value: number = "";',
      'apps/api/src/routes/architecture-probe.test.ts',
    ),
    [],
  );
  assert.deepEqual(
    await reports(
      '// Generated by a tool\nexport {};',
      'apps/web/src/generated/architecture-probe.ts',
    ),
    [],
  );
});
